import importlib
import shutil
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[3]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

# Step modules are numbered (06_...), so import via importlib.
_compose = importlib.import_module("analyses.powerlaw_statistics.06_compose_results")
